const GENERATED_PARAM_REFS = new Set([
  '#/components/parameters/SchoolIdHeader',
  '#/components/parameters/SchoolSlugHeader',
]);
const GENERATED_RESPONSES = {
  400: '#/components/responses/SchoolContextRequired',
  401: '#/components/responses/Unauthorized',
  403: '#/components/responses/Forbidden',
};

function tagFor(p) {
  const seg = p.split('/').filter(Boolean);
  return seg[0] === 'api' ? (seg[1] || 'api') : seg[0];
}

function operationId(method, p) {
  const words = p
    .split('/')
    .filter((s) => s && s !== 'api')
    .map((s) => (s.startsWith('{') ? `by-${s.slice(1, -1)}` : s))
    .join('-')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  return [method, ...words].map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join('');
}

function buildOperation(route, existing = {}) {
  const pathParams = [...route.path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
  const existingParams = (existing.parameters || []).filter(
    (prm) => !(prm.$ref && GENERATED_PARAM_REFS.has(prm.$ref)) && !(prm.in === 'path' && !prm.description)
  );
  const documentedPath = new Map(existingParams.filter((prm) => prm.in === 'path').map((prm) => [prm.name, prm]));
  const parameters = [
    ...pathParams.map((name) => documentedPath.get(name) || { name, in: 'path', required: true, schema: { type: 'string' } }),
    ...existingParams.filter((prm) => prm.in !== 'path'),
    ...(route.schoolContext
      ? [{ $ref: '#/components/parameters/SchoolIdHeader' }, { $ref: '#/components/parameters/SchoolSlugHeader' }]
      : []),
  ];

  const responses = {};
  for (const [code, value] of Object.entries(existing.responses || {})) {
    if (!(value && value.$ref && Object.values(GENERATED_RESPONSES).includes(value.$ref))) responses[code] = value;
  }
  if (!Object.keys(responses).some((c) => /^2/.test(c))) {
    responses[route.method === 'post' ? '201' : '200'] = { description: 'Successful response.' };
  }
  if (route.schoolContext && !responses['400']) responses['400'] = { $ref: GENERATED_RESPONSES[400] };
  if (route.auth !== 'public') {
    if (!responses['401']) responses['401'] = { $ref: GENERATED_RESPONSES[401] };
    if (!responses['403']) responses['403'] = { $ref: GENERATED_RESPONSES[403] };
  }
  if (!responses.default) responses.default = { $ref: '#/components/responses/Error' };

  const op = {
    tags: existing.tags || [tagFor(route.path)],
    operationId: operationId(route.method, route.path),
    summary: existing.summary || `${route.method.toUpperCase()} ${route.path}`,
  };
  if (existing.description) op.description = existing.description;
  op.security = route.auth === 'public' ? [] : [{ BearerAuth: [] }];
  op['x-auth'] = route.auth;
  if (route.roles.length) op['x-roles'] = route.roles;
  op['x-source'] = route.source;
  if (parameters.length) op.parameters = parameters;
  if (existing.requestBody) op.requestBody = existing.requestBody;
  op.responses = Object.fromEntries(
    Object.entries(responses).sort(([a], [b]) => (a === 'default') - (b === 'default') || a.localeCompare(b))
  );
  return op;
}

function buildSpec(existing = {}) {
  const spec = {
    ...BASE,
    info: { ...BASE.info, ...(existing.info || {}) },
    components: {
      ...BASE.components,
      schemas: { ...BASE.components.schemas, ...((existing.components || {}).schemas || {}) },
    },
    paths: {},
  };
  for (const route of extractRoutes()) {
    const prior = ((existing.paths || {})[route.path] || {})[route.method];
    spec.paths[route.path] = spec.paths[route.path] || {};
    spec.paths[route.path][route.method] = buildOperation(route, prior);
  }
  return spec;
}

function renderIndex(spec) {
  const rows = [];
  for (const [p, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const auth = op['x-auth'] === 'public'
        ? 'public'
        : `${op['x-auth']}${op['x-roles'] ? ` (${op['x-roles'].join(', ')})` : ''}`;
      const tenant = (op.parameters || []).some((prm) => prm.$ref === '#/components/parameters/SchoolIdHeader') ? 'yes' : '';
      rows.push(`| \`${method.toUpperCase()}\` | \`${p}\` | ${auth} | ${tenant} |`);
    }
  }
  return [
    INDEX_START,
    '',
    '## Endpoint Index',
    '',
    'Every route the backend serves, generated from [`backend/openapi.json`](../backend/openapi.json).',
    '"Tenant" means the route needs `X-School-ID` or `X-School-Slug`. The sections below add',
    'request/response examples for the most-used endpoints.',
    '',
    '| Method | Path | Auth | Tenant |',
    '|---|---|---|---|',
    ...rows,
    '',
    INDEX_END,
  ].join('\n');
}

function withIndex(markdown, index) {
  const start = markdown.indexOf(INDEX_START.split(' — ')[0]);
  const end = markdown.indexOf(INDEX_END);
  if (start !== -1 && end !== -1) {
    return markdown.slice(0, start) + index + markdown.slice(end + INDEX_END.length);
  }
  // First run: insert after the intro, before the first second-level heading.
  const firstH2 = markdown.search(/^## /m);
  if (firstH2 === -1) return `${markdown.trimEnd()}\n\n${index}\n`;
  return `${markdown.slice(0, firstH2)}${index}\n\n${markdown.slice(firstH2)}`;
}

function main() {
  const check = process.argv.includes('--check');
  const existing = fs.existsSync(SPEC_FILE) ? JSON.parse(fs.readFileSync(SPEC_FILE, 'utf8')) : {};
  const spec = buildSpec(existing);
  const specText = `${JSON.stringify(spec, null, 2)}\n`;
  const markdown = fs.readFileSync(API_SPEC_MD, 'utf8');
  const markdownNext = withIndex(markdown, renderIndex(spec));

  if (check) {
    const stale = [];
    if (!fs.existsSync(SPEC_FILE) || fs.readFileSync(SPEC_FILE, 'utf8') !== specText) stale.push('backend/openapi.json');
    if (markdown !== markdownNext) stale.push('docs/api-spec.md (endpoint index)');
    if (stale.length) {
      console.error(`OpenAPI contract is out of date: ${stale.join(', ')}`);
      console.error('Run `node scripts/openapi/generate.js` and commit the result.');
      process.exit(1);
    }
    console.log('OpenAPI spec and docs index are up to date.');
    return;
  }

  fs.writeFileSync(SPEC_FILE, specText);
  fs.writeFileSync(API_SPEC_MD, markdownNext);
  const count = Object.values(spec.paths).reduce((n, ops) => n + Object.keys(ops).length, 0);
  console.log(`Wrote backend/openapi.json (${count} operations) and the docs/api-spec.md endpoint index.`);
}

module.exports = { buildSpec, renderIndex, SPEC_FILE };

if (require.main === module) main();
