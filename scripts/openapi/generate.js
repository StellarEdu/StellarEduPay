#!/usr/bin/env node
'use strict';

/**
 * Generate backend/openapi.json from the Express routers (issue #1632).
 *
 *   node scripts/openapi/generate.js           # rewrite the spec + docs index
 *   node scripts/openapi/generate.js --check   # exit 1 if either is stale (CI)
 *
 * What is derived from code (always overwritten):
 *   - the set of paths/methods, path parameters
 *   - auth requirements (security, x-auth, x-roles) from requireAdminAuth /
 *     requireSchoolAuth middleware
 *   - school-context headers for routes behind resolveSchool
 *   - the standard 400/401/403 error responses those middlewares produce
 *
 * What is hand-written and preserved across regenerations: summary,
 * description, requestBody, extra parameters, and any responses you add. Edit
 * those directly in backend/openapi.json.
 *
 * The endpoint index in docs/api-spec.md (between the openapi:index markers) is
 * rendered from the spec, so the human-readable reference cannot list a route
 * that does not exist.
 */

