// Creates one student only if the school still has a free seat (#1801).
function createStudentWithinQuota(schoolId, maxStudents, data) {
  return withStudentQuota(schoolId, maxStudents, ({ remaining }) => {
    if (remaining < 1) throw studentQuotaError(maxStudents);
    return Student.create({ schoolId, ...data });
  });
}

async function registerStudent(req, res, next) {
  // Declared in the function scope (not inside try) so the 11000 duplicate-key
  // retry path in catch can read autoGenerated/studentId/name/etc.
  const { schoolId } = req;
  let { studentId, name, class: className, feeAmount, parentEmail, parentPhone } = req.body;

  const autoGenerated = !studentId;
  const MAX_ID_RETRIES = 5;
  let assignedFee;
  let assignedDeadline = null;

  try {
    if (autoGenerated) {
      const { generateStudentId } = require('../utils/generateStudentId');
      studentId = await generateStudentId(MAX_ID_RETRIES, schoolId);
    }

    const existingStudent = await Student.findOne({ schoolId, studentId });
    if (existingStudent) {
      const err = new Error(`A student with ID "${studentId}" already exists`);
      err.code = 'DUPLICATE_STUDENT';
      return next(err);
    }

    // Check if student was previously soft-deleted
    const deletedStudent = await Student.findOne({ schoolId, studentId }).includeDeleted();
    if (deletedStudent && deletedStudent.deletedAt !== null) {
      const err = new Error(`Student ID "${studentId}" was previously deleted. Cannot re-register with the same ID.`);
      err.code = 'STUDENT_PREVIOUSLY_DELETED';
      err.status = 409;
      return next(err);
    }

    const escapedName = name.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const similarStudent = await Student.findOne({
      schoolId,
      name: { $regex: new RegExp(`^${escapedName}$`, 'i') },
      class: className,
    });

    // Always validate that a fee structure exists for the class (#663)
    if (className) {
      const feeStructure = await FeeStructure.findOne({ schoolId, className, deletedAt: null });
      if (!feeStructure) {
        return res.status(400).json({ error: `No fee structure found for class "${className}"`, code: 'FEE_STRUCTURE_NOT_FOUND' });
      }
    }

    assignedFee = feeAmount;
    if (assignedFee == null && className) {
      const feeStructure = await FeeStructure.findOne({ schoolId, className, isActive: true });
      if (feeStructure) {
        assignedFee = feeStructure.feeAmount;
        assignedDeadline = feeStructure.paymentDeadline || null;
      }
    }

    if (assignedFee == null) {
      const err = new Error(
        `No fee amount provided and no fee structure found for class "${className}" in this school. ` +
        `Please create a fee structure first or provide feeAmount.`
      );
      err.code = 'VALIDATION_ERROR';
      return next(err);
    }

    const student = await createStudentWithinQuota(schoolId, req.school?.maxStudents, { studentId, name, class: className, feeAmount: assignedFee, paymentDeadline: assignedDeadline, parentEmail: parentEmail || null, parentPhone: parentPhone || null });

    del(KEYS.studentsAll(), KEYS.student(schoolId, studentId), KEYS.publicStudent(schoolId, studentId));

    // Audit log
    if (req.auditContext) {
      await logAudit({
        schoolId,
        action: 'student_create',
        performedBy: req.auditContext.performedBy,
        targetId: studentId,
        targetType: 'student',
        details: { name, class: className, feeAmount: assignedFee },
        result: 'success',
        ipAddress: req.auditContext.ipAddress,
        userAgent: req.auditContext.userAgent,
      });
    }

    const response = student.toObject ? student.toObject() : { ...student };
    if (similarStudent) {
      response.warning = `A student named "${similarStudent.name}" already exists in class ${className} with ID "${similarStudent.studentId}". This may be a duplicate.`;
    }
    res.status(201).json(response);
  } catch (err) {
    if (err.name === 'ValidationError') {
      return res.status(400).json({ error: err.message, code: 'VALIDATION_ERROR' });
    }
    if (err.code === 11000) {
      if (autoGenerated) {
        // Race-condition on auto-generated ID: retry with a fresh candidate.
        const { generateStudentId } = require('../utils/generateStudentId');
        try {
          studentId = await generateStudentId(MAX_ID_RETRIES, schoolId);
          const student = await createStudentWithinQuota(schoolId, req.school?.maxStudents, { studentId, name, class: className, feeAmount: assignedFee, paymentDeadline: assignedDeadline, parentEmail: parentEmail || null, parentPhone: parentPhone || null });
          const response = student.toObject ? student.toObject() : { ...student };
          return res.status(201).json(response);
        } catch (retryErr) {
          if (retryErr.code === 'STUDENT_ID_GENERATION_FAILED') {
            const e = new Error('Failed to generate a unique student ID after several attempts');
            e.code = 'STUDENT_ID_GENERATION_FAILED';
            e.status = 503;
            return next(e);
          }
          // Another 11000 on retry — give up cleanly
          const e = new Error('Student ID collision could not be resolved');
          e.code = 'DUPLICATE_STUDENT';
          e.status = 409;
          return next(e);
        }
      }
      const e = new Error('Student ID already exists in this school');
      e.code = 'DUPLICATE_STUDENT';
      e.status = 409;
      return next(e);
    }
    next(err);
  }
}

async function getAllStudents(req, res, next) {
  try {
    const page = Math.max(1, parseInt(req.query.page, 10) || 1);
    const limit = Math.max(1, parseInt(req.query.limit, 10) || 50);
    const skip = (page - 1) * limit;

    const filter = { schoolId: req.schoolId };

    if (req.query.class) {
      filter.class = req.query.class;
    }

    if (req.query.status) {
      const status = req.query.status;
      if (status === 'paid') {
        filter.feePaid = true;
      } else if (status === 'unpaid') {
        filter.feePaid = false;
        filter.totalPaid = { $lte: 0 };
      } else if (status === 'partial') {
        filter.feePaid = false;
        filter.totalPaid = { $gt: 0 };
      } else {
        return res.status(400).json({ error: 'status must be paid, unpaid, or partial', code: 'VALIDATION_ERROR' });
      }
    }

    if (req.query.search !== undefined) {
      if (typeof req.query.search !== 'string') {
        return res.status(400).json({ error: 'search must be a string', code: 'VALIDATION_ERROR' });
      }

      const trimmedSearch = req.query.search.trim();
      if (trimmedSearch) {
        const escaped = trimmedSearch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const re = new RegExp(`^${escaped}`, 'i');
        filter.$or = [{ name: re }, { studentId: re }];
      }
    }

    const [students, total] = await Promise.all([
      Student.find(filter, req.admin ? {} : { walletAddress: 0, contactEmail: 0, parentPhone: 0 }).sort({ createdAt: -1 }).skip(skip).limit(limit),
      Student.countDocuments(filter),
    ]);

    res.json({ students, total, page, pages: Math.ceil(total / limit) });
  } catch (err) {
    next(err);
  }
}

async function deleteStudent(req, res, next) {
  try {
    const { studentId } = req.params;

    // The softDelete plugin auto-filters deletedAt: null, so a plain findOne
    // already only returns active (non-deleted) students. No need for a
    // secondary deletedAt check — if the student isn't found here, it either
    // never existed or was already soft-deleted.
    const student = await Student.findOne({ schoolId: req.schoolId, studentId });
    if (!student) {
      // Distinguish "already deleted" from "never existed" so callers get a
      // clear error message rather than a generic 404.
      const alreadyDeleted = await Student.findOne({ schoolId: req.schoolId, studentId }).includeDeleted();
      if (alreadyDeleted) {
        const err = new Error(`Student "${studentId}" has already been deleted`);
        err.code = 'STUDENT_ALREADY_DELETED';
        err.status = 409;
        return next(err);
      }
      const err = new Error('Student not found');
      err.code = 'NOT_FOUND';
      return next(err);
    }

    // Perform soft delete — set deletedAt timestamp instead of removing the document
    await student.softDelete();

    // Mark all associated payments as studentDeleted so they are excluded from
    // live reports while remaining queryable for audit/historical access.
    const Payment = require('../models/paymentModel');
    await Payment.updateMany(
      { schoolId: req.schoolId, studentId },
      { studentDeleted: true },
    );

    del(KEYS.student(req.schoolId, studentId), KEYS.publicStudent(req.schoolId, studentId));

    await logAudit({
      schoolId: req.schoolId,
      action: 'student_delete',
      performedBy: req.auditContext?.performedBy ?? 'unknown',
      targetId: studentId,
      targetType: 'student',
      details: { name: student.name, class: student.class, deletedAt: student.deletedAt },
      result: 'success',
      ipAddress: req.auditContext?.ipAddress ?? null,
      userAgent: req.auditContext?.userAgent ?? null,
    });

    res.json({ message: `Student ${studentId} soft-deleted`, deletedAt: student.deletedAt });
  } catch (err) {
    next(err);
  }
}

/**
 * POST /api/students/:studentId/restore
 *
 * Admin-only. Reverses a soft delete — clears deletedAt on the student and
 * clears the studentDeleted flag on all associated payments so the student and
 * their payment history re-enter normal queries and reports.
 *
 * Audited: every restore is recorded in the audit log.
 */
async function restoreStudent(req, res, next) {
  try {
    const { studentId } = req.params;

    // Must bypass the auto-filter to find soft-deleted documents
    const student = await Student.findOne({ schoolId: req.schoolId, studentId }).includeDeleted();
    if (!student) {
      const err = new Error('Student not found');
      err.code = 'NOT_FOUND';
      return next(err);
    }

    if (student.deletedAt === null) {
      const err = new Error(`Student "${studentId}" is not deleted and cannot be restored`);
      err.code = 'STUDENT_NOT_DELETED';
      err.status = 409;
      return next(err);
    }

    const previousDeletedAt = student.deletedAt;

    // Restore the student — clears deletedAt via the softDelete utility.
    // Restoring adds an active student, so it must also fit the quota (#1801).
    await withStudentQuota(req.schoolId, req.school?.maxStudents, ({ remaining, maxStudents }) => {
      if (remaining < 1) throw studentQuotaError(maxStudents);
      return student.restore();
    });

    // Reinstate payments so they appear in reports again
    const Payment = require('../models/paymentModel');
    await Payment.updateMany(
      { schoolId: req.schoolId, studentId },
      { studentDeleted: false },
    );

    del(KEYS.student(req.schoolId, studentId), KEYS.publicStudent(req.schoolId, studentId));

    await logAudit({
      schoolId: req.schoolId,
      action: 'student_restore',
      performedBy: req.auditContext?.performedBy ?? 'unknown',
      targetId: studentId,
      targetType: 'student',
      details: { name: student.name, class: student.class, previousDeletedAt },
      result: 'success',
      ipAddress: req.auditContext?.ipAddress ?? null,
      userAgent: req.auditContext?.userAgent ?? null,
    });

    res.json({
      message: `Student ${studentId} restored`,
      student: {
        studentId: student.studentId,
        name: student.name,
        class: student.class,
        deletedAt: student.deletedAt,
      },
    });
  } catch (err) {
    next(err);
  }
}

